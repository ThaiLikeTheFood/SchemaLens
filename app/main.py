import time
from typing import List, Dict, Any
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, Field
from sqlalchemy import text

# Import our custom modules
from app.database import AsyncSessionLocal
from app.governance import sanitize_and_limit_sql, SecurityViolation

app = FastAPI(
    title="SchemaLens Gateway (GovMCP)",
    description="Enterprise Schema Discovery & Governance Middleware for AI Agents.",
    version="1.0.0"
)

# --- Pydantic Data Contracts ---

class DiscoverRequest(BaseModel):
    entities: List[str] = Field(..., description="List of entity names to discover (e.g., ['claimants', 'disbursements'])")

class DiscoverResponse(BaseModel):
    schemas: Dict[str, Any]
    message: str

class ExecuteRequest(BaseModel):
    sql_query: str = Field(..., description="The raw SQL query generated by the agent.")

class ExecuteResponse(BaseModel):
    status: str
    rows: List[Dict[str, Any]]
    row_count: int
    execution_time_ms: float
    warnings: List[str] = []

# --- Mock In-Memory Catalog (Simplified for Demo) ---
# In a production environment, this would be dynamically generated via SQLAlchemy inspection.
SCHEMA_CATALOG = {
    "claimants": {
        "columns": ["id (INT, PK)", "ssn_hash (VARCHAR, UNIQUE)", "full_name (VARCHAR)", "claim_status (VARCHAR)"],
        "relations": ["disbursements.claimant_id", "appeals.claimant_id"]
    },
    "disbursements": {
        "columns": ["id (INT, PK)", "claimant_id (INT, FK)", "amount (FLOAT)", "issue_date (DATE)"]
    },
    "appeals": {
        "columns": ["id (INT, PK)", "claimant_id (INT, FK)", "reason (VARCHAR)", "status (VARCHAR)"]
    }
}

# --- API Endpoints ---

@app.post("/mcp/discover", response_model=DiscoverResponse)
async def discover_schema(request: DiscoverRequest):
    """
    Selective Schema Discovery: Returns only the requested table definitions 
    to prevent LLM context window satiation.
    """
    discovered = {}
    for entity in request.entities:
        entity_lower = entity.lower()
        if entity_lower in SCHEMA_CATALOG:
            discovered[entity_lower] = SCHEMA_CATALOG[entity_lower]
            
    if not discovered:
        raise HTTPException(status_code=404, detail="No matching entities found in the enterprise catalog.")
        
    return DiscoverResponse(
        schemas=discovered,
        message=f"Successfully discovered {len(discovered)} entities."
    )

@app.post("/mcp/execute", response_model=ExecuteResponse)
async def execute_query(request: ExecuteRequest):
    """
    Deterministic Governance: Parses, validates, and executes the agent's SQL safely.
    """
    start_time = time.perf_counter()
    warnings = []

    # 1. Pass raw SQL through the AST Security Interceptor
    try:
        safe_sql = sanitize_and_limit_sql(request.sql_query, max_limit=100)
        if safe_sql != request.sql_query:
            warnings.append("Query rewritten: Deterministic LIMIT automatically applied.")
    except SecurityViolation as e:
        # We return a 400 so the agent receives the rejection reason and can self-correct
        raise HTTPException(status_code=400, detail=str(e))

    # 2. Execute against the pooled async database
    try:
        async with AsyncSessionLocal() as session:
            result = await session.execute(text(safe_sql))
            
            # Fetch results and map to dictionaries for JSON serialization
            columns = result.keys()
            rows = [dict(zip(columns, row)) for row in result.fetchall()]
            
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Database execution error: {str(e)}")

    execution_ms = round((time.perf_counter() - start_time) * 1000, 2)

    return ExecuteResponse(
        status="success",
        rows=rows,
        row_count=len(rows),
        execution_time_ms=execution_ms,
        warnings=warnings
    )